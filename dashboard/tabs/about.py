"""Вкладка «О метриках»: краткая справка по дашборду и словарь метрик."""
import streamlit as st


def render(source: str = "") -> None:
    st.subheader("О дашборде")
    st.markdown(
        "Аналитика ранкед-матчей League of Legends: сила чемпионов, предметы, "
        "профили игроков, сдвиги меты по патчам и стили игроков."
    )

    st.markdown("#### Как пользоваться")
    st.markdown(
        "- **Источник данных** (панель «Фильтры» слева) — переключает набор: "
        "`riot_full` (большой архив, 7 патчей), `kaggle` (исторический срез), "
        "`riot_api` (своя свежая выборка). Весь дашборд пересчитывается под выбранный "
        "источник; источники **не смешиваются**.\n"
        "- **⟳ Обновить данные** — сбросить кэш, если данные пересобрали.\n"
        "- **🗎 Скачать CSV** — в шапке каждой таблицы; графики можно сохранить в PNG "
        "через меню «⋯» в правом верхнем углу графика."
    )

    st.markdown("#### Вкладки")
    st.markdown(
        "- **📋 Обзор** — ключевые цифры и авто-инсайты, победители vs проигравшие.\n"
        "- **🏆 Чемпионы** — рейтинг по winrate (с поправкой на число игр), "
        "scatter «убийства vs смерти», аномалии меты.\n"
        "- **🛡️ Предметы** — «покупки × winrate»: правый-верх = популярные и выигрышные.\n"
        "- **👤 Игроки** — распределение по очкам лиги (LP) и карточка игрока.\n"
        "- **⏱ Длительность** — размах длительности матчей и кто сильнее в долгих/коротких играх.\n"
        "- **📊 Мета** — сравнение двух патчей с проверкой статзначимости.\n"
        "- **🧩 Архетипы** — группы игроков по стилю (радар + профиль).\n"
        "- **✅ Качество** — авто-проверки данных."
    )

    st.markdown("#### Словарь метрик")
    st.markdown(
        "- **Winrate** — доля побед.\n"
        "- **Winrate с поправкой на число игр** — не «сырой» процент побед, а "
        "намеренно заниженная (осторожная) оценка с учётом числа игр: берётся "
        "**нижняя граница интервала Уилсона** — нижний край диапазона, где реально "
        "может лежать winrate. Чем меньше игр, тем сильнее занижение: 70% на 5 играх "
        "(скорее везение) опускаются ниже стабильных 54% на 800 играх. По этой метрике "
        "строим рейтинг, чтобы наверх не всплывали случайные лидеры.\n"
        "- **KDA** — (убийства + помощи) ÷ смерти. Общая эффективность в схватках.\n"
        "- **… в минуту** (CS, урон, золото, обзор) — значение, делённое на длину матча: "
        "так сравнимы игроки из коротких и длинных игр.\n"
        "- **p-значение** — насколько вероятно, что различие случайно. p < 0.05 — вряд ли "
        "случайность, изменение реально.\n"
        "- **Аномалия меты** — чемпион, чей winrate статистически значимо отличается от 50%.\n"
        "- **Архетип** — группа игроков со схожим стилем (кластеризация), не официальная "
        "категория Riot."
    )
