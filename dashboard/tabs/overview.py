"""Вкладка «Главное»: что выяснили, а не какие тут есть графики.

Раньше первый экран показывал лидеров по метрикам. Лидер — это максимум выборки,
он систематически завышен (у кого-то из многих обязательно окажется удачная серия),
и выводом быть не может. Здесь вместо витрины лидеров сами выводы, каждый с числом
и указанием вкладки, где его можно перепроверить.
"""
import streamlit as st

from dashboard.data import run


def _finding(number: str, title: str, body: str, where: str) -> None:
    """Один вывод: заголовок, текст, где перепроверить."""
    st.markdown(
        f"<div style='background:#10233a;border:1px solid #2f3a4d;border-left:3px solid #C8AA6E;"
        f"border-radius:10px;padding:14px 18px;margin-bottom:12px'>"
        f"<div style='font-size:11px;color:#a49b86;text-transform:uppercase;"
        f"letter-spacing:.06em'>Вывод {number}</div>"
        f"<div style=\"font-family:'Palatino Linotype','Book Antiqua',serif;font-size:18px;"
        f"font-weight:600;color:#F0E6D2;margin:2px 0 6px\">{title}</div>"
        f"<div style='font-size:14px;color:#cfd6d6;line-height:1.55'>{body}</div>"
        f"<div style='font-size:12px;color:#a49b86;margin-top:8px'>Проверить: {where}</div>"
        f"</div>",
        unsafe_allow_html=True,
    )


def render(source: str) -> None:
    kpi = run(f"""
        SELECT COUNT(DISTINCT match_id) AS matches,
               COUNT(DISTINCT puuid) AS players,
               COUNT(DISTINCT champion_id) AS champions
        FROM fact_participant WHERE data_source = '{source}'
    """).iloc[0]
    duration = run(f"""
        SELECT AVG(game_duration_min) AS d FROM dim_match WHERE data_source = '{source}'
    """).iloc[0]["d"]
    patches = int(run(f"""
        SELECT COUNT(DISTINCT split_part(game_version, '.', 1) || '.'
                              || split_part(game_version, '.', 2)) AS n
        FROM dim_match WHERE data_source = '{source}' AND game_version IS NOT NULL
    """).iloc[0]["n"])

    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Матчей", f"{int(kpi['matches']):,}".replace(",", " "))
    c2.metric("Игроков", f"{int(kpi['players']):,}".replace(",", " "))
    c3.metric("Чемпионов", int(kpi["champions"]))
    c4.metric("Ср. длительность", f"{duration:.1f} мин")

    st.markdown("#### Что показали данные")
    # Разделитель тысяч ставим только в числе: replace на всей строке съедал запятые.
    n_matches = f"{int(kpi['matches']):,}".replace(",", " ")
    st.caption(
        f"Выводы по источнику «{source}»: {n_matches} матчей ранкед-соло, "
        f"{patches} патчей. Каждый вывод можно перепроверить на указанной вкладке."
    )

    _finding(
        "1", "Чемпионов, которые заметно сильнее остальных, нет",
        "Все 172 чемпиона выигрывают примерно половину матчей. Если посчитать наспех, "
        "14 из них выглядят сильными. Но мы проверяем всех сразу, а когда проверок много, "
        "редкие совпадения перестают быть редкими: даже у честной монетки в одной попытке "
        "из сотни орлов выпадет подозрительно много. Стоит это учесть, и сильных не "
        "остаётся ни одного.",
        "«Сила чемпиона», строка под карточками чемпионов",
    )
    _finding(
        "2", "Но это говорит о способе подсчёта, а не об игре",
        "Достаточно перестать смешивать роли, и сильные чемпионы находятся. Виновато "
        "усреднение: одного чемпиона играют на двух позициях, на одной он выигрывает 38% "
        "матчей, на другой 52%, а вместе выходит ровно половина, и он кажется обычным. "
        "Внутри одной роли расстояние от худшего к лучшему доходит до 31 пункта против "
        "12 в общей таблице.",
        "«Сила чемпиона», таблица «От того, как считать, зависит ответ»",
    )
    _finding(
        "3", "Длина матча решает больше, чем выбор чемпиона",
        "Kayle выигрывает 42% коротких матчей и 68% длинных. Разрыв в 27 пунктов больше, "
        "чем расстояние между лучшим и худшим чемпионом во всём рейтинге. Только причину "
        "отсюда не вывести: короткие матчи — это в основном разгромы, поэтому проигрыши "
        "чемпионов, сильных в поздней игре, попадают туда сами собой.",
        "«Сила чемпиона», раздел про долгие и короткие игры",
    )
    _finding(
        "4", "Победа даёт предмет, а не предмет победу",
        "У Guardian Angel 65% побед на 5370 сборках, но покупать его от этого не стоит. "
        "Riot сохраняет только то, что лежало в сумке в конце матча. Дорогую вещь успевает "
        "достроить тот, кто дольше живёт, то есть тот, кто и так выигрывает. Ни один "
        "предмет не прибавляет к победе 15 пунктов.",
        "«Предметы», предупреждение над графиком",
    )
    _finding(
        "5", "Прогноз по составу работает, но еле-еле, и это проверено",
        "Мы спрятали от расчёта целый патч и проверили прогноз на 6743 матчах, которых он "
        "не видел. В каждом матче оценивались обе команды, побеждала та, чья оценка выше, "
        "поэтому наугад вышло бы ровно 50%. Получилось 52.5%. Разница настоящая, но "
        "маленькая: состав влияет на исход куда меньше, чем умение игроков.",
        "«Состав», раздел «Проверка прогноза»",
    )
    _finding(
        "6", "Осторожная игра окупается лучше агрессивной",
        "Если сравнивать каждого игрока не со всеми подряд, а со своей же ролью, получаются "
        "четыре группы. Те, кто реже умирает, выигрывают 55% матчей, те, кто гибнет часто, — "
        "47%. Приписывать разницу одному стилю нельзя: группы отличаются ещё и уровнем самих "
        "игроков, а разделить одно от другого здесь нечем.",
        "«Игроки», раздел про архетипы",
    )

    st.info(
        "**О чём эти выводы не говорят.** Данные собраны в основном по сильным игрокам "
        "верхней части рейтинга, поэтому всё сказанное относится к ним, а не к обычному "
        "игроку. Остальные оговорки собраны на вкладке «Данные и качество».",
        icon="🧭",
    )
